-- ==================== PostgreSQL Primary Init ====================
-- This script initializes the primary server for streaming replication

-- Create replication user (for replica to connect)
CREATE USER replicator WITH REPLICATION ENCRYPTED PASSWORD 'replicator_password';

-- Grant connect permission to replication user
GRANT CONNECT ON DATABASE budget TO replicator;

-- ==================== Replication Configuration ====================
-- These are set via POSTGRES_INITDB_ARGS in docker-compose.yml:
-- -c max_wal_senders=10          (max concurrent replication connections)
-- -c max_replication_slots=10    (max replication slots)
-- -c wal_level=replica           (write-ahead log level for replication)
-- -c hot_standby=on              (allow queries on standby)

-- Configure postgresql.conf for replication (via pg_hba.conf equivalent)
-- The pg_hba.conf is auto-generated by Postgres, but we ensure replicator can connect

