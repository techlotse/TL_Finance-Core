-- ==================== Application Database Setup ====================
-- The budget database and budget user are created by default via POSTGRES_DB and POSTGRES_USER
-- Ensure budget user has proper permissions:

GRANT USAGE ON SCHEMA public TO budget;
GRANT CREATE ON SCHEMA public TO budget;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO budget;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO budget;

